def seed_nlem_2022(db, medicine_model):
    """Insert missing generic names, preserving shop and admin edits."""
    existing = {
        name.casefold()
        for (name,) in db.session.query(medicine_model.name)
        .filter(medicine_model.owner_pharmacy_id.is_(None))
        .all()
    }
    added = 0
    for name in NLEM_2022_NAMES:
        if name.casefold() in existing:
            continue
        db.session.add(
            medicine_model(
                name=name,
                salt=name,
                category="Essential medicine (NLEM 2022)",
                uses="Catalogue entry only. Confirm stock, dispensing requirements, and suitability with a licensed pharmacist.",
            )
        )
        existing.add(name.casefold())
        added += 1
    db.session.commit()
    return added
